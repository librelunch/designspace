"""Gates for the documentation site and for authored prose.

Two groups of law, all of them pure text, all of them always run.

Coverage of the site:

1. the API reference lists every name in `__all__`;
2. every design note carries at least one `>>>` block, so a page cannot become
   prose-only while the doctest gate, which reports green on collecting
   nothing, stays green;
3. every tutorial page's `{code-cell}` blocks execute, in order, in one shared
   namespace. A tutorial's outputs are generated by myst-nb rather than written
   down, so nothing compares them against an expectation; the pages carry
   `assert` statements for the claims their prose makes, and this runs them in
   about two seconds on a plain `pytest -q`, naming the cell that raised. It
   also asserts the `file_format: mystnb` front matter, without which myst-nb
   renders the cells and never executes them.

The prose standard in `CLAUDE.md`, over the trees `_PROSE_SOURCES` names:

4. no U+2014;
5. no decision-ledger entry cited by number outside `DECISIONS.md`;
6. no milestone number outside `PLAN.md` and `PROGRESS.md`;
7. every test module the spec's conformance laws name exists, and every entry
   in the spec's contents list points at one of its headings;
8. every `API.md` section a docstring or comment cites is a heading of
   `API.md`, including its bold run-in form;
9. every conformance law names itself in the module the spec's *Enforced by*
   column assigns it, so the column reads in both directions;
10. no message a user can be shown cites an error-table row. The row number is
    an index into a table that ships with the repository and not with the
    package, and inserting a row renumbers every row below it, so it names
    nothing durable even to a reader holding the table;
11. every error-table row is named by at least one test module. This is the
    counterweight to law 10: the row-to-test correspondence moves into the
    tests, which are read by the people the row numbers are for.

These are the mechanically checkable part of that standard. Register is not
gated: second-person counts and antithesis counts are editorial judgment, and a
threshold test over them would be brittle and would invite gaming.

That the site builds clean under `-W` with `nitpicky = True` is a commit gate
of its own, run as `sphinx-build` directly.
"""

from __future__ import annotations

import ast
import re
import warnings
from pathlib import Path

import pytest

import designspace as ds

_ROOT = Path(__file__).resolve().parent.parent
_DOCS = _ROOT / "docs"
_EXAMPLES = _ROOT / "examples"
_DESIGN_NOTES = sorted((_DOCS / "design-notes").glob("*.md"))
_TUTORIALS = sorted(p for p in (_DOCS / "tutorials").glob("*.md") if p.stem != "index")
_EXAMPLE_SCRIPTS = sorted(_EXAMPLES.glob("*.py"))
# `_build` is gitignored output, not authored prose, and `conf.py` excludes it
# from the build for the same reason.
_DOC_SOURCES = sorted(p for p in _DOCS.rglob("*.md") if "_build" not in p.parts)

_SPEC = _ROOT / "API.md"
_ROOT_MARKDOWN = [
    _SPEC,
    _ROOT / "PLAN.md",
    _ROOT / "PROGRESS.md",
    _ROOT / "DECISIONS.md",
    _ROOT / "CLAUDE.md",
    _ROOT / "README.md",
]
_SOURCE = sorted((_ROOT / "src").rglob("*.py"))
_TESTS = sorted(p for p in (_ROOT / "tests").rglob("*.py") if "__pycache__" not in p.parts)
_CONFIG = [
    _ROOT / "pyproject.toml",
    _ROOT / ".github" / "workflows" / "ci.yml",
    _DOCS / "conf.py",
]

# Every tree the prose laws cover.
_PROSE_SOURCES = [
    *_DOC_SOURCES,
    *_EXAMPLE_SCRIPTS,
    _EXAMPLES / "README.md",
    *_ROOT_MARKDOWN,
    *_SOURCE,
    *_TESTS,
    *_CONFIG,
]

# Spelled as an escape so that this module satisfies the law it defines.
_EM_DASH = "\u2014"
# A decision-ledger entry number. Legal in DECISIONS.md, nowhere else.
_DECISION_CITATION = re.compile(r"\bD-\d+\b")
# A milestone number. Legal in PLAN.md and PROGRESS.md, whose subject it is.
_MILESTONE = re.compile(r"\bM\d+(?:\.\d+)?\b")
# A `tests/...py` path cited in the spec's "Enforced by" column.
_TEST_MODULE = re.compile(r"`(tests/[\w/]+\.py)`")
# A conformance-law row: name, statement, enforcing module.
_LAW_ROW = re.compile(r"^\| `([a-z0-9_]+)` \| .*? \| `(tests/[\w/]+\.py)` \|$", re.MULTILINE)
# A contents entry pointing at a heading of the same document.
_ANCHOR_LINK = re.compile(r"\]\(#([a-z0-9-]+)\)")
_HEADING = re.compile(r"^#{2,3} (.*)$", re.MULTILINE)
# Every heading `API.md` offers a citation, including its bold run-in form.
_ANY_HEADING = re.compile(r"^#{2,6} (.*)$", re.MULTILINE)
_RUN_IN_HEADING = re.compile(r"^(?:[-*]\s+)?\*\*(.+?)\.?\*\*", re.MULTILINE)
# A citation naming an API.md section, with its `>` continuations.
_SECTION_CITATION = re.compile(r'API\.md,\s*"([^"\n]+)"((?:\s*>\s*"[^"\n]+")*)')
_QUOTED = re.compile(r'"([^"\n]+)"')

# An error-table row, cited singly or as a run: "row 12", "rows 6, 7 and 14".
_ROW_CITATION = re.compile(r"\brows?\s+\d+(?:\s*(?:,|and|or|to)\s*\d+)*")
# A citation whose number is interpolated, so the constant ends at "(row ".
# `_check_opaque_compare_types` built one this way and no scan for a spelled
# number could have seen it.
_ROW_INTERPOLATED = re.compile(r"\brows?\s+$")
# The other form a test names a row by: the class the unit suites group by row.
_ROW_CLASS = re.compile(r"\bTestRow(\d+)")
# A document that ships with the repository and not with the package.
_REPO_ONLY_DOC = re.compile(r"\b(?:API|PLAN|PROGRESS|DECISIONS|CLAUDE)\.md\b")
# A private implementation module, as `represent/_build.py`.
_PRIVATE_MODULE = re.compile(r"\b[a-z_]+/_[a-z_]+\.py\b")
_NOT_SELF_CONTAINED = [
    ("a repository-only document", _REPO_ONLY_DOC),
    ("an error-table row", _ROW_CITATION),
    ("a private module", _PRIVATE_MODULE),
]
_NUMBER = re.compile(r"\d+")
# The rows of the spec's error table, by number. The tag is `R`, `V`, or `R`
# qualified, as row 25's `R (warning)` is.
_ERROR_ROW = re.compile(r"^\| (\d+) \| .* \| [RV][^|]* \|$", re.MULTILINE)

# ```{code-cell}\n:tags: [...]\n<source>\n``` is myst-nb's executable block.
# Anchored at the fence so a mention in prose cannot match.
_CODE_CELL = re.compile(
    r"^```\{code-cell\}[^\n]*\n(?P<body>.*?)^```",
    re.MULTILINE | re.DOTALL,
)
# Directive options lead the body and are not Python.
_CELL_OPTION = re.compile(r"\A(?:^:[a-z-]+:.*$\n)+", re.MULTILINE)


def _slug(heading: str) -> str:
    """The anchor a markdown renderer derives from a heading."""
    return re.sub(r"\s+", "-", re.sub(r"[^\w\s-]", "", heading.strip().lower())).strip("-")


def _runtime_strings(path: Path) -> list[tuple[int, str]]:
    """Every string constant in `path` that is not a docstring.

    Docstrings are excluded because a private module's docstring is read by
    a maintainer with `API.md` open. What is left is the text a running
    program can put in front of a user, message templates and their f-string
    fragments among it.
    """
    tree = ast.parse(path.read_text())
    docstrings = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            continue
        first = node.body[0] if node.body else None
        if (
            isinstance(first, ast.Expr)
            and isinstance(first.value, ast.Constant)
            and isinstance(first.value.value, str)
        ):
            docstrings.add(id(first.value))
    return [
        (node.lineno, node.value)
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant)
        and isinstance(node.value, str)
        and id(node) not in docstrings
    ]


def _cited_rows(text: str) -> set[int]:
    """Every error-table row `text` names, by either form a test uses.

    A run is expanded, so "rows 6, 7 and 14" names three. `TestRow12Counts`
    names row 12: the unit suites group a row's cases into one class, which
    is the older and the more precise of the two forms.
    """
    cited = {int(n) for n in _ROW_CLASS.findall(text)}
    for match in _ROW_CITATION.finditer(text):
        cited |= {int(n) for n in _NUMBER.findall(match.group(0))}
    return cited


def _cite_lines(path: Path, pattern: re.Pattern[str]) -> list[str]:
    return [
        f"  line {i}: {line.strip()}"
        for i, line in enumerate(path.read_text().splitlines(), start=1)
        if pattern.search(line)
    ]


def test_reference_lists_every_export() -> None:
    """Every exported name appears in the API reference.

    Without this the reference silently stops covering the surface the
    moment something new is exported.
    """
    text = (_DOCS / "reference.md").read_text()
    missing = [
        name for name in ds.__all__ if name != "__version__" and f"designspace.{name}\n" not in text
    ]
    assert not missing, (
        f"{len(missing)} exported names are absent from docs/reference.md: "
        f"{', '.join(sorted(missing))}"
    )


def test_design_notes_exist() -> None:
    """The design-notes directory is not empty and is reachable from its index."""
    assert _DESIGN_NOTES, "docs/design-notes/ has no pages"
    index = (_DOCS / "design-notes" / "index.md").read_text()
    orphans = [p.stem for p in _DESIGN_NOTES if p.stem != "index" and p.stem not in index]
    assert not orphans, f"design notes missing from the toctree: {', '.join(orphans)}"


@pytest.mark.parametrize("page", _DESIGN_NOTES, ids=[p.stem for p in _DESIGN_NOTES])
def test_design_note_carries_doctests(page: Path) -> None:
    """Every design note except the index carries a runnable example.

    `--doctest-glob=*.md` runs them; this asserts there is something to run,
    so a page cannot quietly become prose-only while the gate reports green.
    """
    if page.stem == "index":
        pytest.skip("the index is a table of contents, not a design note")
    assert ">>>" in page.read_text(), (
        f"{page.name} carries no `>>>` example. A design note argues a "
        f"trade-off, and the argument is grounded in code that runs."
    )


